Future<void> main() async {
  final root = Directory.current;
  final codepoints =
      (jsonDecode(File('${root.path}/tool/icons/codepoints.json').readAsStringSync()) as Map<String, dynamic>)
          .cast<String, int>();
  final missing = _icons.where((name) => !codepoints.containsKey(name)).toList();
  if (missing.isNotEmpty) {
    stderr.writeln('Unknown Lucide icons: ${missing.join(', ')}');
    exitCode = 1;
    return;
  }

  final subset = _fontSubsetPath();
  final process = await Process.start(subset, ['assets/fonts/AppIcons.ttf', 'tool/icons/lucide.ttf']);
  process.stdin.writeln(_icons.map((name) => codepoints[name]).join(' '));
  await process.stdin.close();
  final output = await process.stdout.transform(utf8.decoder).join();
  final errors = await process.stderr.transform(utf8.decoder).join();
  if (await process.exitCode != 0) {
    stderr.writeln('font-subset failed:\n$output$errors');
    exitCode = 1;
    return;
  }

  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/build_icons.dart. Do not edit by hand.')
    ..writeln('// Lucide icons (ISC, assets/fonts/Lucide-LICENSE.txt) subset into AppIcons.ttf.')
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('abstract final class AppIcons {');
  for (final name in [..._icons]..sort()) {
    buffer.writeln("  static const IconData ${_dartName(name)} = IconData(${codepoints[name]}, fontFamily: 'AppIcons');");
  }
  buffer.writeln('}');
  File('${root.path}/lib/core/widgets/app_icons.dart').writeAsStringSync(buffer.toString());
  final size = File('${root.path}/assets/fonts/AppIcons.ttf').lengthSync();
  stdout.writeln('AppIcons.ttf: ${_icons.length} icons, ${(size / 1024).toStringAsFixed(1)} KB');
}

String _dartName(String kebab) {
  final parts = kebab.split('-');
  return parts.first + parts.skip(1).map((part) => part[0].toUpperCase() + part.substring(1)).join();
}

/// font-subset ships with the Flutter engine artifacts, next to the Dart SDK
/// that runs this script.
String _fontSubsetPath() {
  final fromEnv = Platform.environment['FONT_SUBSET'];
  if (fromEnv != null) return fromEnv;
  final dartBin = File(Platform.resolvedExecutable).parent; // bin/cache/dart-sdk/bin
  final cache = dartBin.parent.parent; // bin/cache
  final platform = Platform.isWindows
      ? 'windows-x64'
      : Platform.isMacOS
      ? 'darwin-x64'
      : 'linux-x64';
  return '${cache.path}/artifacts/engine/$platform/font-subset${Platform.isWindows ? '.exe' : ''}';
}
